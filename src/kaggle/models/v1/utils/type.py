import pandas as pd
import torch
from pydantic import BaseModel, Field
from torch.utils.data import Dataset
from transformers import PreTrainedTokenizerBase


class ChatData(BaseModel):
    """
    A Pydantic model representing a single chat data entry.
    """

    # input data
    id: int = Field(..., description="Unique identifier for the chat entry")
    prompt: str = Field(..., description="Prompt or question sent to the bot")
    response_a: str = Field(..., description="Response generated by the Model A")
    response_b: str = Field(..., description="Response generated by the Model B")

    # evaluation data
    label: int | None = Field(
        ...,
        description="Label indicating the preferred response (0 for Model A, 1 for Model B, 2 for tied)",
    )


class ChatDataset(Dataset):
    def __init__(
        self,
        df: pd.DataFrame,
        tokenizer: PreTrainedTokenizerBase,
        max_length: int = 512,
    ):
        self.df = df
        self.tokenizer = tokenizer
        self.max_length = max_length

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]

        prompt = str(row["prompt"])
        response_a = str(row["response_a"])
        response_b = str(row["response_b"])

        # [CLS] Prompt [SEP] Response A [SEP] Response B [SEP]
        # TODO: Consider using a more sophisticated method to combine the prompt and responses, such as using special tokens or formatting.
        text = f"Prompt: {prompt}\n\nModel A: {response_a}\n\nModel B: {response_b}"

        encoding = self.tokenizer(
            text,
            max_length=self.max_length,
            padding="max_length",
            truncation=True,
            return_tensors="pt",
        )

        item = {
            "input_ids": encoding["input_ids"].flatten(),
            "attention_mask": encoding["attention_mask"].flatten(),
        }

        # Add label if it exists in the row
        if "label" in row:
            item["labels"] = torch.tensor(row["label"], dtype=torch.long)

        return item
