"""入力データの前処理と Dataset 定義.

このコンペの入力は `prompt` / `response_a` / `response_b` の 3 パートで、
合計長が 512 token を超えることが多いため、単純な末尾切り詰めだと
`response_b` が丸ごと失われる。ここではパートごとにトークン予算を割り振り、
各パートを head/tail で切り詰める。

また A/B の提示順に偏り（position bias）が出やすいコンペなので、
学習時は responses を入れ替えてラベルを反転させる swap 拡張を任意で有効化できる。
"""

from __future__ import annotations

import random

import pandas as pd
import torch
from pydantic import BaseModel, Field
from torch.nn.utils.rnn import pad_sequence
from torch.utils.data import Dataset
from transformers import PreTrainedTokenizerBase

from kaggle.models.v1.config import NUM_LABELS, TARGET_COLUMNS

# [CLS] prompt [SEP] response_a [SEP] response_b
# CLS と SEP 2 つぶらぶらせるので、特殊トークンは 3 つを確保する
SPECIAL_TOKENS_TOTAL = 3

# どのパートが何かをモデルに伝えるための接頭辞（予算内に含める）
PART_PREFIXES = {
    "prompt": "Prompt: ",
    "response_a": "Model A: ",
    "response_b": "Model B: ",
}


class ChatData(BaseModel):
    """
    A Pydantic model representing a single chat data entry.
    """

    # input data
    id: int = Field(..., description="Unique identifier for the chat entry")
    prompt: str = Field(..., description="Prompt or question sent to the bot")
    response_a: str = Field(..., description="Response generated by the Model A")
    response_b: str = Field(..., description="Response generated by the Model B")

    # evaluation data（test.csv にはラベルがないので None を許容する）
    label: int | None = Field(
        default=None,
        ge=0,
        le=NUM_LABELS - 1,
        description=(
            "Label indicating the preferred response "
            "(0 for Model A, 1 for Model B, 2 for tied)"
        ),
    )


def label_from_flags(row: pd.Series) -> int:
    """one-hot の target カラムからラベル索引（0: A, 1: B, 2: tie）へ変換する."""
    flags = [bool(row[column]) for column in TARGET_COLUMNS]
    if sum(flags) != 1:
        raise ValueError(
            f"id={row.get('id')}: {TARGET_COLUMNS} の有効値が 1 個ではありません: {flags}"
        )
    return flags.index(True)


def token_budgets(max_length: int, prompt_ratio: float) -> tuple[int, int, int]:
    """prompt / response_a / response_b に割り当てるトークン予算を計算する.

    応答は 2 つ同長で扱う（swap 拡張と合わせて対称にする）。
    """
    if max_length <= SPECIAL_TOKENS_TOTAL + 3:
        raise ValueError(f"max_length が短すぎます: {max_length}")
    if not 0.0 <= prompt_ratio < 1.0:
        raise ValueError(
            f"prompt_ratio は [0, 1) の範囲で指定してください: {prompt_ratio}"
        )

    budget = max_length - SPECIAL_TOKENS_TOTAL
    prompt_budget = int(budget * prompt_ratio)
    response_budget = budget - prompt_budget
    response_a_budget = response_budget // 2
    response_b_budget = response_budget - response_a_budget
    return prompt_budget, response_a_budget, response_b_budget


def truncate_ids(ids: list[int], budget: int, head_ratio: float) -> list[int]:
    """予算を超える token を head/tail に配分して切り詰める.

    応答の末尾（結論や謝罪文）が捨てられがちなので、既定では head 70% / tail 30% で残す。
    """
    if budget <= 0:
        return []
    if len(ids) <= budget:
        return ids

    head = int(budget * head_ratio)
    head = max(1, min(head, budget - 1)) if budget > 1 else 1
    tail = budget - head
    return ids[:head] + ids[-tail:]


def build_encoding(
    tokenizer: PreTrainedTokenizerBase,
    prompt: str,
    response_a: str,
    response_b: str,
    max_length: int,
    prompt_ratio: float,
    head_ratio: float,
) -> dict[str, torch.Tensor]:
    """3 パートを 1 系列に組み立てる（パートごとに切り詰め）."""
    cls_token_id = tokenizer.cls_token_id or tokenizer.bos_token_id
    sep_token_id = tokenizer.sep_token_id or tokenizer.eos_token_id
    if cls_token_id is None or sep_token_id is None:
        raise ValueError("tokenizer に cls/bos または sep/eos が定義されていません")

    prompt_budget, response_a_budget, response_b_budget = token_budgets(
        max_length=max_length, prompt_ratio=prompt_ratio
    )

    # prompt は冒頭（指示本体）が重要なので head を優先する
    prompt_ids = truncate_ids(
        tokenizer.encode(PART_PREFIXES["prompt"] + prompt, add_special_tokens=False),
        budget=prompt_budget,
        head_ratio=1.0,
    )
    response_a_ids = truncate_ids(
        tokenizer.encode(
            PART_PREFIXES["response_a"] + response_a, add_special_tokens=False
        ),
        budget=response_a_budget,
        head_ratio=head_ratio,
    )
    response_b_ids = truncate_ids(
        tokenizer.encode(
            PART_PREFIXES["response_b"] + response_b, add_special_tokens=False
        ),
        budget=response_b_budget,
        head_ratio=head_ratio,
    )

    input_ids = (
        [cls_token_id]
        + prompt_ids
        + [sep_token_id]
        + response_a_ids
        + [sep_token_id]
        + response_b_ids
    )
    return {
        "input_ids": torch.tensor(input_ids, dtype=torch.long),
        "attention_mask": torch.ones(len(input_ids), dtype=torch.long),
    }


class ChatDataset(Dataset):
    """prompt / response_a / response_b を 1 系列に変換する Dataset.

    パディングは collate_fn（バッチ単位）で行う。`padding="max_length"` だと
    全サンプルが 512 token になり、実質 1.5 倍の計算を捨てている。
    """

    def __init__(
        self,
        df: pd.DataFrame,
        tokenizer: PreTrainedTokenizerBase,
        max_length: int = 512,
        prompt_ratio: float = 0.15,
        head_ratio: float = 0.7,
        swap_augment_p: float = 0.0,
        seed: int = 42,
    ):
        self.df = df.reset_index(drop=True)
        self.tokenizer = tokenizer
        self.max_length = max_length
        self.prompt_ratio = prompt_ratio
        self.head_ratio = head_ratio
        self.swap_augment_p = swap_augment_p
        self.seed = seed
        self.epoch = 0
        self.has_label = "label" in self.df.columns

    def __len__(self):
        return len(self.df)

    def set_epoch(self, epoch: int) -> None:
        """epoch ごとに swap の当たり方を変える（検証集は拡張しないので呼ばない）."""
        self.epoch = epoch

    def _swap(self, idx: int) -> bool:
        """epoch と index から決定的に swap を決める（DataLoader worker でも再現可能）."""
        if self.swap_augment_p <= 0.0:
            return False
        rng = random.Random(f"{self.seed}-{self.epoch}-{idx}")
        return rng.random() < self.swap_augment_p

    def __getitem__(self, idx):
        row = self.df.iloc[idx]

        prompt = str(row["prompt"])
        response_a = str(row["response_a"])
        response_b = str(row["response_b"])

        # [CLS] Prompt [SEP] Model A [SEP] Model B
        # swap 拡張: 提示順を入れ替え、A/B のラベルだけ反転させる（tie はそのまま）
        swap = self._swap(idx)
        if swap:
            response_a, response_b = response_b, response_a

        item = build_encoding(
            tokenizer=self.tokenizer,
            prompt=prompt,
            response_a=response_a,
            response_b=response_b,
            max_length=self.max_length,
            prompt_ratio=self.prompt_ratio,
            head_ratio=self.head_ratio,
        )

        if self.has_label:
            label = int(row["label"])
            if swap and label in (0, 1):
                label = 1 - label
            item["labels"] = torch.tensor(label, dtype=torch.long)

        return item


def make_collate_fn(tokenizer: PreTrainedTokenizerBase):
    """バッチ内で最も長い系列に合わせて動的にパディングする."""
    pad_token_id = tokenizer.pad_token_id
    if pad_token_id is None:
        raise ValueError("tokenizer に pad_token が定義されていません")

    def collate_fn(items: list[dict]) -> dict[str, torch.Tensor]:
        batch = {
            "input_ids": pad_sequence(
                [item["input_ids"] for item in items],
                batch_first=True,
                padding_value=pad_token_id,
            ),
            "attention_mask": pad_sequence(
                [item["attention_mask"] for item in items],
                batch_first=True,
                padding_value=0,
            ),
        }
        if "labels" in items[0]:
            batch["labels"] = torch.stack([item["labels"] for item in items])
        return batch

    return collate_fn
